//! Generate the Rust half of USD's schema data (SPEC D15).
//!
//! `rusd-scene/schemas/rusd_types_manifest.usda` is the one declaration of the schema
//! graph: per identifier its `schemaKind` and its *direct* bases, the same two fields
//! a C++ schema library ships in `plugInfo.json`. `rusd-scene` reads it at runtime into
//! `UsdSchemaRegistry`, whose `IsA` walks it. This script reads the **same file** at
//! build time and writes the Rust types a script's signatures are checked against:
//!
//! - one unit struct per schema, with `Schema::NAME` the identifier USD knows;
//! - `impl IsA<Base> for Derived` for every ancestor, transitively — so a Rust trait
//!   bound answers exactly what `UsdSchemaRegistry::IsA` answers, at compile time;
//! - one unit struct per API schema, with `ApiSchema::NAME`.
//!
//! Nothing here is a second source of truth: the relation is the manifest's, and
//! `tests/schema_graph.rs` cross-checks every generated pair against the registry the
//! runtime builds from the same text.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

/// One entry of the manifest: its identifier, its kind, and its direct bases.
struct Entry {
    kind: String,
    bases: Vec<String>,
}

fn main() {
    let manifest = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../rusd-scene/schemas/rusd_types_manifest.usda");
    println!("cargo:rerun-if-changed={}", manifest.display());
    let text = std::fs::read_to_string(&manifest)
        .unwrap_or_else(|e| panic!("read {}: {e}", manifest.display()));
    let entries = parse(&text);

    // A base may name a schema another family owns (`Typed`, `APISchemaBase`): the
    // registry crosses into that family, so the Rust types have to exist too. They
    // are abstract, and they declare no bases of their own here.
    let mut names: Vec<String> = entries.keys().cloned().collect();
    for entry in entries.values() {
        for base in &entry.bases {
            if !entries.contains_key(base) && !names.contains(base) {
                names.push(base.clone());
            }
        }
    }
    names.sort();

    let mut out = String::from(
        "// @generated by crates/rusd-script/build.rs from rusd_types_manifest.usda.\n\
         // Do not edit: the schema graph is the manifest's, and this is its Rust half.\n\n",
    );
    let mut typed: Vec<&String> = Vec::new();
    let mut apis: Vec<&String> = Vec::new();
    for name in &names {
        let entry = entries.get(name);
        let kind = entry.map(|e| e.kind.as_str()).unwrap_or("abstractTyped");
        if kind.ends_with("API") {
            apis.push(name);
            writeln!(out, "/// The `{name}` API schema — an interface, not a class.").unwrap();
            writeln!(out, "pub struct {name};").unwrap();
            writeln!(
                out,
                "impl crate::schema::ApiSchema for {name} {{ const NAME: &'static str = \"{name}\"; }}"
            )
            .unwrap();
            continue;
        }
        typed.push(name);
        let concrete = kind == "concreteTyped";
        writeln!(out, "/// The `{name}` schema (`{kind}`).").unwrap();
        writeln!(out, "pub struct {name};").unwrap();
        writeln!(
            out,
            "impl crate::schema::Schema for {name} {{\n    const NAME: &'static str = \"{name}\";\n    const CONCRETE: bool = {concrete};\n}}"
        )
        .unwrap();
        // `IsA` is reflexive and transitive: the closure of `bases`, plus the schema
        // itself. One impl per pair, so a trait bound is the whole answer.
        for ancestor in ancestors(name, &entries) {
            writeln!(out, "impl crate::schema::IsA<{ancestor}> for {name} {{}}").unwrap();
        }
    }

    // The pairs, as data: what the cross-check test compares against `IsA`.
    writeln!(out, "\n/// Every typed schema this family declares.").unwrap();
    writeln!(out, "pub const TYPED: &[&str] = &[").unwrap();
    for name in &typed {
        writeln!(out, "    \"{name}\",").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "\n/// Every API schema this family declares.").unwrap();
    writeln!(out, "pub const APIS: &[&str] = &[").unwrap();
    for name in &apis {
        writeln!(out, "    \"{name}\",").unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "\n/// Every `(derived, base)` pair the generated `IsA` impls hold.").unwrap();
    writeln!(out, "pub const IS_A: &[(&str, &str)] = &[").unwrap();
    for name in &typed {
        for ancestor in ancestors(name, &entries) {
            writeln!(out, "    (\"{name}\", \"{ancestor}\"),").unwrap();
        }
    }
    writeln!(out, "];").unwrap();

    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("usd_schemas.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("write {}: {e}", dest.display()));
}

/// The manifest's entries, by identifier. The file is the small, stable shape USD's
/// schema data has: `def "Name" { uniform token schemaKind = "…" uniform token[]
/// bases = [...] }`, one block per schema, `#` comments to end of line.
fn parse(text: &str) -> BTreeMap<String, Entry> {
    let mut entries = BTreeMap::new();
    let mut current: Option<String> = None;
    let mut kind = String::new();
    let mut bases: Vec<String> = Vec::new();
    for line in text.lines() {
        let line = line.split('#').next().unwrap_or("").trim();
        if let Some(rest) = line.strip_prefix("def \"") {
            if let Some(name) = current.take() {
                entries.insert(name, Entry { kind: kind.clone(), bases: std::mem::take(&mut bases) });
            }
            current = Some(rest.trim_end_matches('"').to_owned());
            kind.clear();
            continue;
        }
        if line == "}" {
            if let Some(name) = current.take() {
                entries.insert(name, Entry { kind: kind.clone(), bases: std::mem::take(&mut bases) });
            }
            continue;
        }
        if let Some(rest) = line.strip_prefix("uniform token schemaKind") {
            kind = quoted(rest).unwrap_or_default();
        }
        if let Some(rest) = line.strip_prefix("uniform token[] bases") {
            bases = quoted_list(rest);
        }
    }
    if let Some(name) = current.take() {
        entries.insert(name, Entry { kind, bases });
    }
    entries
}

/// The first `"…"` in `s`.
fn quoted(s: &str) -> Option<String> {
    let start = s.find('"')? + 1;
    let end = start + s[start..].find('"')?;
    Some(s[start..end].to_owned())
}

/// Every `"…"` in `s`.
fn quoted_list(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = s;
    while let Some(start) = rest.find('"') {
        let after = &rest[start + 1..];
        let Some(len) = after.find('"') else { break };
        out.push(after[..len].to_owned());
        rest = &after[len + 1..];
    }
    out
}

/// `name` itself and every schema reachable through `bases`, transitively.
fn ancestors(name: &str, entries: &BTreeMap<String, Entry>) -> Vec<String> {
    let mut seen: Vec<String> = vec![name.to_owned()];
    let mut queue: Vec<String> = vec![name.to_owned()];
    while let Some(next) = queue.pop() {
        for base in entries.get(&next).map(|e| e.bases.clone()).unwrap_or_default() {
            if !seen.contains(&base) {
                seen.push(base.clone());
                queue.push(base);
            }
        }
    }
    seen.sort();
    seen
}
